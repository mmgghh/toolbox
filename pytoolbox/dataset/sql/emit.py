"""Writing a CREATE TABLE + INSERT script for either dialect."""

from __future__ import annotations

from collections.abc import Sequence

from pytoolbox.dataset import naming
from pytoolbox.dataset.schema import Column
from pytoolbox.dataset.sql import table as table_module
from pytoolbox.dataset.sql.dialects import Dialect
from pytoolbox.dataset.sql.table import TableSpec


def build(
    spec: TableSpec,
    columns: Sequence[Column],
    records: Sequence[dict],
    dialect: Dialect,
    origin: str = "",
    root: str = "",
) -> str:
    """Return the whole script: comments, DDL, indexes and inserts."""
    wide = table_module.wide_columns(columns, records)
    blocks = [
        _banner(spec, columns, records, dialect, origin, root),
        create_table(spec, columns, dialect, wide),
    ]
    indexes = create_indexes(spec, dialect)
    if indexes:
        blocks.append(indexes)
    blocks.append(inserts(spec, columns, records, dialect))
    return "\n\n".join(block for block in blocks if block) + "\n"


def _banner(
    spec: TableSpec,
    columns: Sequence[Column],
    records: Sequence[dict],
    dialect: Dialect,
    origin: str,
    root: str,
) -> str:
    source = origin or "input"
    if root:
        source += f" (--root {root})"
    return (
        f"-- Generated by pytoolbox pydata from {source}.\n"
        f"-- Dialect: {dialect.name}. "
        f"{len(records)} rows, {len(columns)} columns."
    )


def create_table(
    spec: TableSpec,
    columns: Sequence[Column],
    dialect: Dialect,
    wide: set[str] = frozenset(),
) -> str:
    """The DROP (if asked for) and CREATE TABLE statements."""
    lines = []
    if spec.if_exists == "replace":
        lines.append(f"DROP TABLE IF EXISTS {dialect.quote(spec.name)};")

    exists_clause = "IF NOT EXISTS " if spec.if_exists == "append" else ""
    lines.append(f"CREATE TABLE {exists_clause}{dialect.quote(spec.name)} (")

    quoted = [dialect.quote(column.name) for column in columns]
    width = max((len(name) for name in quoted), default=0)
    key = set(spec.primary_key)
    definitions = []
    for column, name in zip(columns, quoted):
        sql_type = dialect.sql_type(column.type, wide=column.name in wide, nested=spec.nested)
        # A primary key is never null, whatever the data happened to contain.
        nullable = column.nullable and column.name not in key
        suffix = "" if nullable else " NOT NULL"
        definitions.append(f"    {name.ljust(width)} {sql_type}{suffix}")
    if spec.primary_key:
        keys = ", ".join(dialect.quote(name) for name in spec.primary_key)
        definitions.append(f"    PRIMARY KEY ({keys})")
    lines.append(",\n".join(definitions))
    lines.append(");")
    return "\n".join(lines)


def create_indexes(spec: TableSpec, dialect: Dialect) -> str:
    """One CREATE INDEX per ``--index`` and ``--unique-index``."""
    statements = []
    for group in spec.indexes:
        statements.append(_index(spec.name, group, dialect, unique=False))
    for group in spec.unique_indexes:
        statements.append(_index(spec.name, group, dialect, unique=True))
    return "\n".join(statements)


def _index(table: str, group: tuple[str, ...], dialect: Dialect, unique: bool) -> str:
    name = naming.index_name(table, group)
    columns = ", ".join(dialect.quote(column) for column in group)
    keyword = "CREATE UNIQUE INDEX" if unique else "CREATE INDEX"
    return f"{keyword} {dialect.quote(name)} ON {dialect.quote(table)} ({columns});"


def inserts(
    spec: TableSpec,
    columns: Sequence[Column],
    records: Sequence[dict],
    dialect: Dialect,
) -> str:
    """Multi-row INSERT statements, wrapped in one transaction."""
    if not records:
        return ""
    names = ", ".join(dialect.quote(column.name) for column in columns)
    prefix = f"INSERT INTO {dialect.quote(spec.name)} ({names}) VALUES"

    statements = []
    for start in range(0, len(records), spec.batch):
        chunk = records[start : start + spec.batch]
        rows = [
            "    ("
            + ", ".join(
                dialect.literal(record.get(column.source), column.type, nested=spec.nested)
                for column in columns
            )
            + ")"
            for record in chunk
        ]
        statements.append(prefix + "\n" + ",\n".join(rows) + ";")
    return "BEGIN;\n\n" + "\n\n".join(statements) + "\n\nCOMMIT;"
